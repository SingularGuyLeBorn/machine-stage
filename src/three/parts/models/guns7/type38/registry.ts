const t38Rifling: InstanceLayout = ({ index }) =>
  new THREE.Matrix4().makeTranslation(0, STAGE_Y, 0).multiply(
    new THREE.Matrix4().makeRotationZ((index * Math.PI) / 2),
  );

const t38Round: InstanceLayout = ({ index, constants: c }) => {
  const y = index === 0 ? 0 : c.ROUND_Y0 - (index - 1) * c.ROUND_PITCH;
  const z = index === 0 ? 0.0005 : c.MAG_Z;
  return new THREE.Matrix4().makeTranslation(0, y + c.STAGE_Y, z);
};

const t38FiringSpring: InstanceLayout = ({ index, count }) => {
  const z0 = -0.16;
  const z1 = -0.058;
  const t = count <= 1 ? 0 : index / (count - 1);
  return new THREE.Matrix4().makeTranslation(0, STAGE_Y, z0 + (z1 - z0) * t);
};

const t38MagSpring: InstanceLayout = ({ index, count }) => {
  const y0 = -0.092;
  const y1 = -0.078;
  const t = count <= 1 ? 0 : index / (count - 1);
  const q = new THREE.Quaternion().setFromEuler(new THREE.Euler(-Math.PI / 2, 0, 0));
  return new THREE.Matrix4().compose(
    new THREE.Vector3(0, STAGE_Y + y0 + (y1 - y0) * t, -0.11),
    q,
    new THREE.Vector3(1, 1, 1),
  );
};

const t38BrassRest: InstanceLayout = ({ index }) => {
  const q = new THREE.Quaternion().setFromEuler(new THREE.Euler(0, index * 1.1, Math.PI / 2));
  const x = 0.06 + (index % 4) * 0.028;
  const z = -0.14 + Math.floor(index / 4) * 0.05 + (index % 3) * 0.012;
  return new THREE.Matrix4().compose(
    new THREE.Vector3(x, constants.BRASS_FLOOR_Y + 0.0059, z),
    q,
    new THREE.Vector3(1, 1, 1),
  );
};

export const type38Layouts: Record<string, InstanceLayout> = {
  t38Rifling,
  t38Round,
  t38FiringSpring,
  t38MagSpring,
  t38BrassRest,
};

