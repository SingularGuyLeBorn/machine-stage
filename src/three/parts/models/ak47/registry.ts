// ---------------------------------------------------------------------------
// 实例布局
//
// 弹药：第 0 发在弹膛（case 底缘 z=0），第 i≥1 发在弹匣弧位 s=(i-1)/2
// （双列交错 + 向抱弹口收敛）。所有子件（底火/火药/弹头/铅套/钢芯）都
// 挂同一套弧位姿态，只是沿弹轴的局部偏移不同。
// ---------------------------------------------------------------------------
/** 各子件相对弹壳底缘的沿轴偏移（米）。 */
const AMMO_OFFSET = {
  case: 0,
  primer: 0.0002,
  propellant: 0.019,
  bullet: 0.0425, // 被甲中心（弹壳口内 9.4mm 卡收）
  lead: 0.0405, // 铅套中心（被甲圆柱段内）
  steel: 0.0345, // 钢芯中心（被甲底部）
} as const;

/** 第 index 发在「装填静止态」的姿态矩阵（模型空间）。
 *  第 0 发在弹膛（弹心 z 0.0281，轴平行枪膛轴）；
 *  其余在弹匣：弹心在堆叠弧位、弹轴沿弧法向（香蕉匣里弹随弧倾斜），
 *  round 局部原点 = 弹壳底缘 → 沿自身轴后移 28.1mm。 */
export function ak47RoundMatrix(index: number, zOffset: number): THREE.Matrix4 {
  if (index === 0) {
    return new THREE.Matrix4().makeTranslation(0, SY, 0.0281 + zOffset);
  }
  const { pos, alpha } = magRoundTransform(index);
  const m = new THREE.Matrix4().makeRotationX(alpha);
  m.setPosition(pos[0], pos[1] + SY, pos[2]);
  m.multiply(new THREE.Matrix4().makeTranslation(0, 0, -0.0281 + zOffset));
  return m;
}

const SY = AK47_CONSTANTS.STAGE_Y;

function roundLayout(key: keyof typeof AMMO_OFFSET): InstanceLayout {
  return ({ index }) => ak47RoundMatrix(index, AMMO_OFFSET[key]);
}

/** 复进簧圈：静止态等距铺在机匣支座（z -0.229）与枪机框簧肩（z -0.13）之间。 */
const recoilSpringCoil: InstanceLayout = ({ index, count }) => {
  const lo = -0.215; // 机匣尾端支座
  const hi = -0.085; // 枪机框簧肩（motion 会随后坐压缩）
  const pitch = (hi - lo) / count;
  return new THREE.Matrix4().makeTranslation(0, SY, lo + (index + 0.5) * pitch);
};

/** 托弹簧圈：沿弹匣堆叠弧铺在底板（末发下方）与满弹托弹板之间。 */
const magSpringCoil: InstanceLayout = ({ index, count }) => {
  const u0 = magRoundArc(29) + 0.008;
  const u1 = u0 + 0.011;
  const u = u0 + ((index + 0.5) / count) * (u1 - u0);
  const { pos, alpha } = magSlotTransform(u);
  const m = new THREE.Matrix4().makeRotationX(Math.PI / 2 + alpha);
  m.setPosition(pos[0], pos[1] + SY, pos[2]);
  return m;
};

/** 弹壳池静止布局（动画会逐发改写；这里给一个可检验的基准散布）。 */
const brassRest: InstanceLayout = ({ index }) => {
  const { position, quaternion } = brassPose(index);
  return new THREE.Matrix4().compose(position, quaternion, new THREE.Vector3(1, 1, 1));
};

export function makeAk47Layouts(): Record<string, InstanceLayout> {
  return {
    ak47RoundCase: roundLayout("case"),
    ak47RoundPrimer: roundLayout("primer"),
    ak47RoundPowder: roundLayout("propellant"),
    ak47RoundBullet: roundLayout("bullet"),
    ak47RoundLead: roundLayout("lead"),
    ak47RoundSteel: roundLayout("steel"),
    ak47RecoilSpringCoil: recoilSpringCoil,
    ak47MagSpringCoil: magSpringCoil,
    ak47BrassRest: brassRest,
  };
}

