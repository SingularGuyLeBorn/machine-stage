/** 铆钉族：沿接收器四角环周分布（18 颗）。 */
const receiverRivet: InstanceLayout = ({ index, count }) => {
  const half = 0.032;
  const z0 = -0.36;
  const z1 = 0.06;
  // 两列：每列 9 颗沿 z 均布
  const col = Math.floor(index / (count / 2));
  const along = (index % (count / 2)) / (count / 2 - 1);
  const x = col === 0 ? -half : half;
  const z = z0 + 0.02 + along * (z1 - z0 - 0.04);
  const y = index % 2 === 0 ? 0.032 : -0.032;
  return new THREE.Matrix4().makeTranslation(x, y + SY, z);
};

/** 复进簧圈：静止态铺在后挡板（z -0.35）与枪机簧肩（z -0.1）之间。 */
const recoilSpringCoil: InstanceLayout = ({ index, count }) => {
  const lo = -0.35;
  const hi = -0.1;
  const pitch = (hi - lo) / count;
  return new THREE.Matrix4().makeTranslation(0, SY, lo + (index + 0.5) * pitch);
};

/** 弹链节静止布局。 */
const beltLinkLayout: InstanceLayout = ({ index }) => beltLinkMatrix(index);

/** 链上弹六分件。 */
function beltRoundLayout(key: keyof typeof M2_OFFSET): InstanceLayout {
  return ({ index }) => beltRoundMatrix(index, M2_OFFSET[key]);
}

/** 弹壳池静止布局（motion 逐帧改写）。 */
const brassRest: InstanceLayout = ({ index }) => {
  const { position, quaternion } = brassPose(index);
  return new THREE.Matrix4().compose(position, quaternion, new THREE.Vector3(1, 1, 1));
};

export function makeM2hbLayouts(): Record<string, InstanceLayout> {
  return {
    m2hbReceiverRivet: receiverRivet,
    m2hbRecoilSpringCoil: recoilSpringCoil,
    m2hbBeltLink: beltLinkLayout,
    m2hbBeltCase: beltRoundLayout("case"),
    m2hbBeltBullet: beltRoundLayout("bullet"),
    m2hbBeltLead: beltRoundLayout("lead"),
    m2hbBeltSteel: beltRoundLayout("steel"),
    m2hbBeltPowder: beltRoundLayout("propellant"),
    m2hbBrassRest: brassRest,
  };
}

